'use strict';
const C=require('./raid-critical-label');
module.exports=(l,s)=>{
 const names={attack:'ATTACK',guard:'GUARD',thrust:'THRUST',parry:'PARRY',cleanse:'CURSE LIFTED'};
 let title=l.damage>0?(l.critical?C.label(C.tier(l))+' HIT! ':'HIT! ')+l.damage+' DAMAGE':names[l.action]||'ACTION COMPLETE';
 if(l.ultimate)title='RESONANT WAVE SLASH! '+l.damage+' DAMAGE';
 if(l.action==='prayer')title='BLESSING / SMITE EMPOWERED, DEF +100%';if(l.ultimate&&s.config.job==='paladin')title='JUDGMENT! '+l.damage+' DAMAGE';
 if(l.charmBlocked)title='CHARMED! ATTACK INTERRUPTED';
 if(l.action==='prayer')title='BLESSING / SMITE EMPOWERED, DEF +100%';
 if(l.action==='thrust')title=(l.warrior?.deep?'DEEP THRUST':'THRUST')+'! '+l.damage+' DAMAGE';if(l.action==='slash')title='SLASH! '+l.damage+' DAMAGE';
 if(l.emergencyEvaded)title='EMERGENCY EVADE!';
 if(l.parryResult==='perfect')title='PERFECT PARRY!';
 else if(l.parryResult==='success')title='PARRY SUCCESS!';
 else if(l.parryResult==='failed')title='PARRY FAILED!';
 else if(l.parryResult==='no_contact')title='PARRY / NO STRIKE';
 const moves={normal:(l.hand||'').toUpperCase()+' FIST',flurry:'FLURRY',heavy:'CRUSHING BLOW',warning:'FISTS RAISED',mark_warning:'CURSE FORMING',mark:'SANDSTORM',struggle_start:'SHOCKWAVE CHARGING',struggle:'SHOCKWAVE CHARGING',struggle_end:'SHOCKWAVE',opening:'BOSS STAGGERED',recovery:'BOSS RECOVERING'};
 const loss=(l.incoming||0)+(l.dot||0)+(l.mechanicDamage||0)+(l.selfDamage||0);
 let boss=(moves[l.phase]||'COLOSSUS')+(loss?' / HP -'+loss:' / HP -0');
 if(l.curseInterruptedNow)boss='CURSE INTERRUPTED!';
 if(l.shockwaveInterrupted||(l.phase==='struggle_end'&&l.struggleSkills>=2))boss='SHOCKWAVE INTERRUPTED!';
 if(l.emergencyEvaded)boss='DANGER EVADED / NO DAMAGE';
 const effects=[];
 if(l.paladin?.smiteHeal)effects.push('DIVINE SMITE HEAL +'+l.paladin.smiteHeal);
 if(l.action==='smash')title=(l.paladin?.divineSmite?'DIVINE SMITE':'SMITE')+'! '+l.damage+' DAMAGE';
 if(l.warrior?.overheat)effects.push('OVERHEAT ACTIVATED / '+l.warrior.overheatTurns+' TURNS / THRUST 0 ENERGY');else if(l.warrior?.overheatEnded)effects.push('OVERHEAT ENDED');
 if(l.counterDamage>0)effects.push('COUNTER'+(C.counterTier(l,s)>0?' '+C.label(C.counterTier(l,s)):'')+'! '+l.counterDamage);
 const energy=require('./raid-energy-log').format(l);
 if(energy)effects.push(energy);
 if(l.heal>0)effects.push('HEAL +'+l.heal);
 if(l.dot>0)effects.push('CURSE -'+l.dot);
 if(['perfect','success'].includes(l.parryResult))effects.push('ATK BOOST');
 if(l.shockwaveInterrupted)effects.push('GROGGY / 2 TURNS');
 const severe=loss>=Math.max(20,Math.ceil((s?.stats?.hp||100)*.15));
 return [(l.critical||l.parryResult==='perfect'?'## ':'### ')+title,severe?'## '+boss:'**'+boss+'**','-# '+(effects.join(' · ')||'—')];
};
